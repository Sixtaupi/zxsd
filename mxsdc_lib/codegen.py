"""Emit deterministic immutable C schema descriptor tables."""

from .common import ABI_VERSIONS, VERSION, cstr, ident


def abi_checks(bindings=False):
    """Reject stale generated headers AND sources before reading any descriptors."""
    checks = []
    for kind in (("runtime", "descriptor", "binding") if bindings else ("runtime", "descriptor")):
        macro = "MXSD_%s_ABI_VERSION" % kind.upper()
        epoch = ABI_VERSIONS[kind]
        checks += [
            "#if !defined(%s) || %s != %d" % (macro, macro, epoch),
            '#error "mxsdc requires %s=%d; regenerate with a matching compiler/runtime"'
            % (macro, epoch),
            "#endif",
        ]
    return "\n".join(checks) + "\n"


def abi_guard(sid, bindings=False):
    """Emit real symbol references so precompiled objects cannot bypass epoch checks."""
    kinds = ("runtime", "descriptor", "binding") if bindings else ("runtime", "descriptor")
    return (
        "/** Require matching runtime epochs even when this object is precompiled. */\n"
        "static void %s_require_abi(void)\n{\n" % sid
        + "".join("\tmxsd_%s_abi_%d();\n" % (kind, ABI_VERSIONS[kind]) for kind in kinds)
        + "}\n"
    )


def generate(stem, m):
    """Render a compiled schema model as deterministic C header/source text."""
    guard = ident(stem).upper() + "_MXSD_H"
    sid = ident(stem)

    def symbol(key, collection):
        if "|" not in key:
            return ident(key)
        uri, name = key.split("|", 1)
        duplicates = sum(1 for candidate in collection if candidate.split("|", 1)[-1] == name)
        return ident(name) if duplicates == 1 else ident(uri + "_" + name)

    type_symbol = lambda key: symbol(key, m["types"])
    root_symbol = lambda key: symbol(key, m["order"])
    license_header = (
        "/*\n * Copyright (c) 2026 mxsd contributors\n *\n"
        " * SPDX-License-Identifier: Apache-2.0\n */\n\n"
    )
    file_doc = license_header + (
        "/**\n * @file\n * @brief Generated mxsd validator for the " + stem + " schema.\n"
        f" *\n * @note Generated by mxsdc {VERSION}. Do not edit manually.\n */\n\n"
    )
    decl = [
        f"/**\n * @brief Validate XML against the default {stem} root.\n *\n * @param[in] xml NUL-terminated XML document.\n *\n * @return A structured validation result.\n */\nmxsd_result_t {sid}_validate(const char *xml);",
        f"/**\n * @brief Validate XML against any global root in {stem}.\n *\n * This helper is intended for document collections where the selected global\n * element is not known by the caller.\n *\n * @param[in] xml NUL-terminated XML document.\n *\n * @return A structured validation result.\n */\nmxsd_result_t {sid}_validate_document(const char *xml);",
        f"/**\n * @brief Initialize streaming validation for the default {stem} root.\n *\n * @param[out] stream Caller-owned streaming context.\n *\n * @return A structured validation result.\n */\nmxsd_result_t {sid}_stream_init(mxsd_stream_t *stream);",
        f"/**\n * @brief Get the default generated schema descriptor.\n *\n * @return Generated immutable schema descriptor.\n */\nconst mxsd_schema_t *{sid}_schema(void);",
    ] + [
        f"/**\n * @brief Validate XML whose root element is {m['globals'][n]['name']}.\n *\n * @param[in] xml NUL-terminated XML document.\n *\n * @return A structured validation result.\n */\nmxsd_result_t {sid}_{root_symbol(n)}_validate(const char *xml);\n\n/**\n * @brief Initialize streaming validation for root {m['globals'][n]['name']}.\n *\n * @param[out] stream Caller-owned streaming context.\n *\n * @return A structured validation result.\n */\nmxsd_result_t {sid}_{root_symbol(n)}_stream_init(mxsd_stream_t *stream);\n\n/**\n * @brief Get the generated descriptor for root {m['globals'][n]['name']}.\n *\n * @return Generated immutable schema descriptor.\n */\nconst mxsd_schema_t *{sid}_{root_symbol(n)}_schema(void);"
        for n in m["order"]
    ]
    h = (
        file_doc
        + f"#ifndef {guard}\n#define {guard}\n\n#include <mxsd.h>\n\n"
        + abi_checks()
        + "\n"
        + "\n\n".join(decl)
        + "\n\n#endif\n"
    )
    out = [
        file_doc.rstrip(),
        "",
        f'#include "{stem}.mxsd.h"',
        "",
        "#include <limits.h>",
        "",
        abi_checks(),
        abi_guard(sid),
    ]
    for n, t in m["types"].items():
        out.append(f"static const mxsd_{t['kind']}_t type_{type_symbol(n)};")
    out.append("")

    def simple_ref(ref):
        if not ref:
            return "{MXSD_T_STRING, NULL}"
        pointer = f"&type_{type_symbol(ref['simple'])}" if ref.get("simple") else "NULL"
        return "{%s, %s}" % (ref["base"], pointer)

    particle_serial = [0]

    def element_init(e):
        ty = e["type"]
        cp = f"&type_{type_symbol(ty['complex'])}" if ty["complex"] else "NULL"
        sp = f"&type_{type_symbol(ty['simple'])}" if ty["simple"] else "NULL"
        mx = "ULONG_MAX" if e["max"] is None else str(e["max"]) + "UL"
        ns = cstr(e["ns"]) if e["ns"] else "NULL"
        default = cstr(e["default"]) if e.get("default") is not None else "NULL"
        fixed = cstr(e["fixed"]) if e.get("fixed") is not None else "NULL"
        head = e.get("substitution_head")
        hn = cstr(head[0]) if head else "NULL"
        hns = cstr(head[1]) if head and head[1] else "NULL"
        return f"{{{cstr(e['name'])}, {ty['base']}, {cp}, {e['min']}UL, {mx}, {sp}, {ns}, {default}, {fixed}, {1 if e.get('nillable') else 0}, {1 if e.get('abstract') else 0}, {e.get('block',0)}, {hn}, {hns}}}"

    def emit_particle(p, prefix):
        particle_serial[0] += 1
        serial = particle_serial[0]
        tag = f"{prefix}_{serial}"
        maximum = "ULONG_MAX" if p["max"] is None else str(p["max"]) + "UL"
        if p["kind"] == "element":
            out.append(
                f"static const mxsd_element_t particle_element_{tag} = {element_init(p['element'])};"
            )
            return f"{{MXSD_PARTICLE_ELEMENT, {p['min']}UL, {maximum}, &particle_element_{tag}, NULL, 0, NULL}}"
        if p["kind"] == "any":
            process = {
                "strict": "MXSD_PROCESS_STRICT",
                "lax": "MXSD_PROCESS_LAX",
                "skip": "MXSD_PROCESS_SKIP",
            }[p["process"]]
            target = cstr(p.get("target")) if p.get("target") else "NULL"
            out.append(
                f"static const mxsd_wildcard_t wildcard_{tag} = {{{cstr(p['namespace'])}, {target}, {process}}};"
            )
            return f"{{MXSD_PARTICLE_ANY, {p['min']}UL, {maximum}, NULL, NULL, 0, &wildcard_{tag}}}"
        child_inits = [emit_particle(child, tag) for child in p["children"]]
        out.append(
            f"static const mxsd_particle_t particle_children_{tag}[] = {{\n  "
            + ",\n  ".join(child_inits)
            + "\n};"
        )
        kind = {
            "sequence": "MXSD_PARTICLE_SEQUENCE",
            "choice": "MXSD_PARTICLE_CHOICE",
            "all": "MXSD_PARTICLE_ALL",
        }[p["kind"]]
        return f"{{{kind}, {p['min']}UL, {maximum}, NULL, particle_children_{tag}, {len(child_inits)}, NULL}}"

    for n, t in m["types"].items():
        ni = type_symbol(n)
        if t["kind"] == "simple":
            if t["enums"]:
                out.append(
                    f"static const char *const enum_{ni}[] = {{"
                    + ", ".join(cstr(x) for x in t["enums"])
                    + "};"
                )
            if t.get("enum_namespaces"):
                out.append(
                    f"static const char *const enum_namespaces_{ni}[] = {{"
                    + ", ".join(cstr(x) if x else "NULL" for x in t["enum_namespaces"])
                    + "};"
                )
            if t.get("members"):
                out.append(
                    f"static const mxsd_simple_ref_t members_{ni}[] = {{"
                    + ", ".join(simple_ref(x) for x in t["members"])
                    + "};"
                )
            if t.get("patterns"):
                out.append(
                    f"static const char *const patterns_{ni}[] = {{"
                    + ", ".join(cstr(pattern) for pattern in t["patterns"])
                    + "};"
                )
            f = t["facets"]
            fmap = {
                "length": "MXSD_F_LENGTH",
                "minLength": "MXSD_F_MIN_LENGTH",
                "maxLength": "MXSD_F_MAX_LENGTH",
                "minInclusive": "MXSD_F_MIN_INCLUSIVE",
                "maxInclusive": "MXSD_F_MAX_INCLUSIVE",
                "minExclusive": "MXSD_F_MIN_EXCLUSIVE",
                "maxExclusive": "MXSD_F_MAX_EXCLUSIVE",
                "pattern": "MXSD_F_PATTERN",
                "totalDigits": "MXSD_F_TOTAL_DIGITS",
                "fractionDigits": "MXSD_F_FRACTION_DIGITS",
            }
            flag = " | ".join(v for k, v in fmap.items() if k in f) or "0"
            val = lambda k: cstr(str(f[k])) if k in f else "NULL"
            enum = f"enum_{ni}" if t["enums"] else "NULL"
            member_ptr = f"members_{ni}" if t.get("members") else "NULL"
            pattern_ptr = f"patterns_{ni}" if t.get("patterns") else "NULL"
            enum_namespace_ptr = f"enum_namespaces_{ni}" if t.get("enum_namespaces") else "NULL"
            base_ptr = f"&type_{type_symbol(t['base_ref'])}" if t.get("base_ref") else "NULL"
            tn = cstr(t["type_name"]) if t.get("type_name") else "NULL"
            tns = cstr(t["type_ns"]) if t.get("type_ns") else "NULL"
            out.append(
                f"static const mxsd_simple_t type_{ni} = {{{t['base']}, {flag}, {f.get('length',0)}, {f.get('minLength',0)}, {f.get('maxLength',0)}, {val('minInclusive')}, {val('maxInclusive')}, {val('minExclusive')}, {val('maxExclusive')}, {val('pattern')}, {enum}, {len(t['enums'])}, {t.get('whitespace','MXSD_WS_PRESERVE')}, {t.get('variety','MXSD_SIMPLE_ATOMIC')}, {simple_ref(t.get('item'))}, {member_ptr}, {len(t.get('members',[]))}, {base_ptr}, {t.get('derivation',0)}, {t.get('final',0)}, {tn}, {tns}, {pattern_ptr}, {len(t.get('patterns',[]))}, {enum_namespace_ptr}, {f.get('totalDigits',0)}, {f.get('fractionDigits',0)}}};\n"
            )
        else:
            es = t["elements"]
            ats = t["attributes"]
            if es:
                out.append(f"static const mxsd_element_t elements_{ni}[] = {{")
                for e in es:
                    out.append("  " + element_init(e) + ",")
                out.append("};")
            if ats:
                out.append(f"static const mxsd_attribute_t attributes_{ni}[] = {{")
                for a in ats:
                    ty = a["type"]
                    sp = f"&type_{type_symbol(ty['simple'])}" if ty["simple"] else "NULL"
                    ns = cstr(a["ns"]) if a["ns"] else "NULL"
                    default = cstr(a["default"]) if a.get("default") is not None else "NULL"
                    fixed = cstr(a["fixed"]) if a.get("fixed") is not None else "NULL"
                    out.append(
                        f"  {{{cstr(a['name'])}, {ty['base']}, {1 if a['required'] else 0}, {sp}, {ns}, {default}, {fixed}}},"
                    )
                out.append("};")
            particle_ptr = "NULL"
            if t.get("particle"):
                root_init = emit_particle(t["particle"], ni)
                out.append(f"static const mxsd_particle_t particle_{ni} = {root_init};")
                particle_ptr = f"&particle_{ni}"
            any_attribute_ptr = "NULL"
            if t.get("any_attribute"):
                wildcard = t["any_attribute"]
                process = {
                    "strict": "MXSD_PROCESS_STRICT",
                    "lax": "MXSD_PROCESS_LAX",
                    "skip": "MXSD_PROCESS_SKIP",
                }[wildcard["process"]]
                target = cstr(wildcard.get("target")) if wildcard.get("target") else "NULL"
                out.append(
                    f"static const mxsd_wildcard_t any_attribute_{ni} = {{{cstr(wildcard['namespace'])}, {target}, {process}}};"
                )
                any_attribute_ptr = f"&any_attribute_{ni}"
            ep = f"elements_{ni}" if es else "NULL"
            ap = f"attributes_{ni}" if ats else "NULL"
            mx = "ULONG_MAX" if t["group_max"] is None else str(t["group_max"]) + "UL"
            content = t.get("simple_content")
            content_ptr = (
                f"&type_{type_symbol(content['simple'])}"
                if content and content.get("simple")
                else "NULL"
            )
            content_type = content["base"] if content else "MXSD_T_STRING"
            base_ptr = f"&type_{type_symbol(t['base_ref'])}" if t.get("base_ref") else "NULL"
            tn = cstr(t["type_name"]) if t.get("type_name") else "NULL"
            tns = cstr(t["type_ns"]) if t.get("type_ns") else "NULL"
            out.append(
                f"static const mxsd_complex_t type_{ni} = {{{ep}, {len(es)}, {ap}, {len(ats)}, {t['model']}, {t['group_min']}UL, {mx}, {content_ptr}, {content_type}, {1 if content else 0}, {1 if t.get('abstract') else 0}, {particle_ptr}, {any_attribute_ptr}, {base_ptr}, {t.get('derivation',0)}, {t.get('final',0)}, {tn}, {tns}, {1 if t.get('mixed') else 0}, {1 if t.get('any_type') else 0}, {t.get('block',0)}}};\n"
            )
    if m["order"]:
        out.append("static const mxsd_global_element_t global_elements[] = {")
        for n in m["order"]:
            e = m["globals"][n]
            ty = e["type"]
            cp = f"&type_{type_symbol(ty['complex'])}" if ty["complex"] else "NULL"
            sp = f"&type_{type_symbol(ty['simple'])}" if ty["simple"] else "NULL"
            ns = cstr(e["ns"]) if e["ns"] else "NULL"
            default = cstr(e["default"]) if e.get("default") is not None else "NULL"
            fixed = cstr(e["fixed"]) if e.get("fixed") is not None else "NULL"
            head = e.get("substitution_head")
            hn = cstr(head[0]) if head else "NULL"
            hns = cstr(head[1]) if head and head[1] else "NULL"
            out.append(
                f"  {{{cstr(e['name'])}, {ns}, {ty['base']}, {cp}, {sp}, {default}, {fixed}, {1 if e.get('nillable') else 0}, {1 if e.get('abstract') else 0}, {e.get('block',0)}, {hn}, {hns}}},"
            )
        out.append("};")
    if m.get("global_attributes"):
        out.append("static const mxsd_global_attribute_t global_attributes[] = {")
        for attribute in m["global_attributes"]:
            ty = attribute["type"]
            sp = f"&type_{type_symbol(ty['simple'])}" if ty["simple"] else "NULL"
            ns = cstr(attribute["ns"]) if attribute["ns"] else "NULL"
            default = cstr(attribute["default"]) if attribute.get("default") is not None else "NULL"
            fixed = cstr(attribute["fixed"]) if attribute.get("fixed") is not None else "NULL"
            out.append(
                f"  {{{cstr(attribute['name'])}, {ns}, {ty['base']}, {sp}, {default}, {fixed}}},"
            )
        out.append("};")
        global_attribute_pointer = "global_attributes"
    else:
        global_attribute_pointer = "NULL"
    named = [(key, value) for key, value in m["types"].items() if value.get("type_name")]
    if named:
        out.append("static const mxsd_named_type_t named_types[] = {")
        for key, value in named:
            ns = cstr(value["type_ns"]) if value.get("type_ns") else "NULL"
            if value["kind"] == "complex":
                out.append(
                    f"  {{{cstr(value['type_name'])}, {ns}, MXSD_T_COMPLEX, &type_{type_symbol(key)}, NULL}},"
                )
            else:
                out.append(
                    f"  {{{cstr(value['type_name'])}, {ns}, {value['base']}, NULL, &type_{type_symbol(key)}}},"
                )
        out.append("};")
        named_pointer = "named_types"
    else:
        named_pointer = "NULL"
    if m.get("notations"):
        out.append("static const mxsd_notation_t notations[] = {")
        for notation in m["notations"]:
            namespace = cstr(notation["ns"]) if notation["ns"] else "NULL"
            public = cstr(notation["public"]) if notation["public"] is not None else "NULL"
            system = cstr(notation["system"]) if notation["system"] is not None else "NULL"
            out.append(f"  {{{cstr(notation['name'])}, {namespace}, {public}, {system}}},")
        out.append("};")
        notation_pointer = "notations"
    else:
        notation_pointer = "NULL"
    identity_names = {}

    def emit_xpath(xpath, prefix):
        alternatives = xpath.get("alternatives", [])
        if alternatives:
            values = [
                emit_xpath(alternative, f"{prefix}_alternative_{index}")
                for index, alternative in enumerate(alternatives)
            ]
            out.append(
                f"static const mxsd_xpath_t xpath_alternatives_{prefix}[] = {{"
                + ", ".join(values)
                + "};"
            )
            return f"{{NULL, 0, 0, 0, xpath_alternatives_{prefix}, {len(alternatives)}}}"
        if xpath["steps"]:
            out.append(f"static const mxsd_xpath_step_t xpath_steps_{prefix}[] = {{")
            for step in xpath["steps"]:
                step_name = cstr(step["name"]) if step["name"] else "NULL"
                step_ns = cstr(step["ns"]) if step["ns"] else "NULL"
                out.append(f"  {{{step_name}, {step_ns}}},")
            out.append("};")
            steps = f"xpath_steps_{prefix}"
        else:
            steps = "NULL"
        return f"{{{steps}, {len(xpath['steps'])}, {1 if xpath['descendant'] else 0}, {1 if xpath['attribute'] else 0}, NULL, 0}}"

    for n in m["order"]:
        constraints = m["globals"][n].get("identities", [])
        ni = root_symbol(n)
        if not constraints:
            continue
        entries = []
        for ci, constraint in enumerate(constraints):
            scope = emit_xpath(constraint["scope"], f"{ni}_{ci}_scope")
            selector = emit_xpath(constraint["selector"], f"{ni}_{ci}_selector")
            field_values = []
            for fi, field in enumerate(constraint["fields"]):
                field_values.append(emit_xpath(field, f"{ni}_{ci}_field_{fi}"))
            out.append(
                f"static const mxsd_xpath_t identity_fields_{ni}_{ci}[] = {{"
                + ", ".join(field_values)
                + "};"
            )
            kind = {
                "unique": "MXSD_ID_UNIQUE",
                "key": "MXSD_ID_KEY",
                "keyref": "MXSD_ID_KEYREF",
            }[constraint["kind"]]
            entries.append(
                f"{{{cstr(constraint['name'])}, {kind}, {scope}, {selector}, identity_fields_{ni}_{ci}, {len(field_values)}, {constraint['refer_index']}}}"
            )
        out.append(
            f"static const mxsd_identity_t identities_{ni}[] = {{\n  "
            + ",\n  ".join(entries)
            + "\n};"
        )
        identity_names[n] = f"identities_{ni}"
    for n in m["order"]:
        e = m["globals"][n]
        ty = e["type"]
        cp = f"&type_{type_symbol(ty['complex'])}" if ty["complex"] else "NULL"
        sp = f"&type_{type_symbol(ty['simple'])}" if ty["simple"] else "NULL"
        ns = cstr(e["ns"]) if e["ns"] else "NULL"
        identities = identity_names.get(n, "NULL")
        count = len(e.get("identities", []))
        default = cstr(e["default"]) if e.get("default") is not None else "NULL"
        fixed = cstr(e["fixed"]) if e.get("fixed") is not None else "NULL"
        out.append(
            f"static const mxsd_schema_t schema_{root_symbol(n)} = {{{cstr(e['name'])}, {ty['base']}, {cp}, {sp}, {ns}, {identities}, {count}, global_elements, {len(m['order'])}, {global_attribute_pointer}, {len(m.get('global_attributes',[]))}, {named_pointer}, {len(named)}, {default}, {fixed}, {1 if e.get('nillable') else 0}, {1 if e.get('abstract') else 0}, {e.get('block',0)}, {notation_pointer}, {len(m.get('notations',[]))}}};"
        )
    if not m["order"]:
        out.append(
            f"static const mxsd_schema_t schema_unbound = {{NULL, MXSD_T_COMPLEX, NULL, NULL, NULL, NULL, 0, NULL, 0, {global_attribute_pointer}, {len(m.get('global_attributes',[]))}, {named_pointer}, {len(named)}, NULL, NULL, 0, 0, 0, {notation_pointer}, {len(m.get('notations',[]))}}};"
        )
        out += [
            "",
            f"mxsd_result_t {sid}_validate(const char *xml) {{ {sid}_require_abi(); return mxsd_validate(&schema_unbound, xml); }}",
            f"mxsd_result_t {sid}_validate_document(const char *xml) {{ {sid}_require_abi(); return mxsd_validate(&schema_unbound, xml); }}",
            f"mxsd_result_t {sid}_stream_init(mxsd_stream_t *stream) {{ {sid}_require_abi(); return mxsd_stream_init(stream, &schema_unbound); }}",
            f"const mxsd_schema_t *{sid}_schema(void) {{ {sid}_require_abi(); return &schema_unbound; }}",
        ]
        return h, "\n".join(out) + "\n"
    first = root_symbol(m["order"][0])
    any_root = [
        f"mxsd_result_t {sid}_validate_document(const char *xml) {{",
        "  mxsd_result_t result;",
        f"  {sid}_require_abi();",
    ]
    for n in m["order"]:
        any_root += [
            f"  result = mxsd_validate(&schema_{root_symbol(n)}, xml);",
            "  if (result.code != MXSD_ERR_WRONG_ROOT) return result;",
        ]
    any_root += ["  return result;", "}"]
    out += (
        [
            "",
            f"mxsd_result_t {sid}_validate(const char *xml) {{ {sid}_require_abi(); return mxsd_validate(&schema_{first}, xml); }}",
        ]
        + any_root
        + [
            f"mxsd_result_t {sid}_stream_init(mxsd_stream_t *stream) {{ {sid}_require_abi(); return mxsd_stream_init(stream, &schema_{first}); }}",
            f"const mxsd_schema_t *{sid}_schema(void) {{ {sid}_require_abi(); return &schema_{first}; }}",
        ]
        + [
            f"mxsd_result_t {sid}_{root_symbol(n)}_validate(const char *xml) {{ {sid}_require_abi(); return mxsd_validate(&schema_{root_symbol(n)}, xml); }}\nmxsd_result_t {sid}_{root_symbol(n)}_stream_init(mxsd_stream_t *stream) {{ {sid}_require_abi(); return mxsd_stream_init(stream, &schema_{root_symbol(n)}); }}\nconst mxsd_schema_t *{sid}_{root_symbol(n)}_schema(void) {{ {sid}_require_abi(); return &schema_{root_symbol(n)}; }}"
            for n in m["order"]
        ]
    )
    return h, "\n".join(out) + "\n"
