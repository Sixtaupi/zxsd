static unsigned unicode_category(uint32_t codepoint)
{
	size_t low = 0u;
	size_t high = sizeof(category_ranges) / sizeof(category_ranges[0]);
	while (low + 1u < high) {
		size_t middle = low + (high - low) / 2u;
		if (category_ranges[middle].start <= codepoint)
			low = middle;
		else
			high = middle;
	}
	return category_ranges[low].category;
}

int mxsd_unicode_property_matches(uint32_t codepoint, const char *property, size_t length)
{
	static const char categories[][3] = {
		"Lu",
		"Ll",
		"Lt",
		"Lm",
		"Lo",
		"Mn",
		"Mc",
		"Me",
		"Nd",
		"Nl",
		"No",
		"Pc",
		"Pd",
		"Ps",
		"Pe",
		"Pi",
		"Pf",
		"Po",
		"Zs",
		"Zl",
		"Zp",
		"Sm",
		"Sc",
		"Sk",
		"So",
		"Cc",
		"Cf",
		"Cs",
		"Co",
		"Cn",
	};
	unsigned category;
	size_t low, high;
	if (codepoint > 0x10FFFFu || property == NULL)
		return 0;
	category = unicode_category(codepoint);
	if (length == 1u)
		return categories[category][0] == property[0];
	if (length == 2u && property[0] != 'I')
		return categories[category][0] == property[0] &&
		       categories[category][1] == property[1];
	if (length <= 2u || property[0] != 'I' || property[1] != 's')
		return 0;
	property += 2;
	length -= 2u;
	if (length == 10u && memcmp(property, "PrivateUse", 10u) == 0)
		return (codepoint >= 0xE000u && codepoint <= 0xF8FFu) ||
		       (codepoint >= 0xF0000u && codepoint <= 0xFFFFDu) ||
		       (codepoint >= 0x100000u && codepoint <= 0x10FFFDu);
	if (length == 8u && memcmp(property, "Specials", 8u) == 0 &&
	    codepoint == 0xFEFFu)
		return 1;
	low = 0u;
	high = sizeof(unicode_blocks) / sizeof(unicode_blocks[0]);
	while (low < high) {
		size_t middle = low + (high - low) / 2u;
		size_t name_length = strlen(unicode_blocks[middle].name);
		size_t common = name_length < length ? name_length : length;
		int comparison = memcmp(unicode_blocks[middle].name, property, common);
		if (comparison == 0 && name_length != length)
			comparison = name_length < length ? -1 : 1;
		if (comparison < 0)
			low = middle + 1u;
		else if (comparison > 0)
			high = middle;
		else
			return codepoint >= unicode_blocks[middle].first &&
			       codepoint <= unicode_blocks[middle].last;
	}
	return 0;
}
